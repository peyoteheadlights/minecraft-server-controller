# ---------------------------------------------------------------- live server
class TLSServer:
    def __init__(self, config):
        self.config = config
        certfile, keyfile = resolve_tls(config)
        self.port = int(config.get("network.port"))
        uvicorn_config = uvicorn.Config(
            create_app(config), host="127.0.0.1", port=self.port,
            ssl_certfile=certfile, ssl_keyfile=keyfile,
            log_level="warning", access_log=False,
        )
        self.server = uvicorn.Server(uvicorn_config)
        self.thread = threading.Thread(target=self.server.run, daemon=True)

    def __enter__(self):
        self.thread.start()
        deadline = time.time() + 20
        while time.time() < deadline and not self.server.started:
            time.sleep(0.05)
        if not self.server.started:
            raise RuntimeError("the TLS server did not start")
        return self

    def __exit__(self, *exc):
        self.server.should_exit = True
        self.thread.join(timeout=20)


