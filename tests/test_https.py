def test_http_listener_only_redirects_and_refuses_api_calls():
    app = create_redirect_app(8765)
    from fastapi.testclient import TestClient

    with TestClient(app) as client:
        response = client.get("/api/status", follow_redirects=False)
        assert response.status_code == 308
        assert response.headers["location"].startswith("https://")
        # a POST is refused rather than redirected, so credentials are never
        # re-sent by a client that follows the redirect
        refused = client.post("/api/auth/login", json={"username": "a", "password": "b"})
        assert refused.status_code == 400
        assert "HTTPS" in refused.json()["detail"]
