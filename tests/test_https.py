# ---------------------------------------------------------------- generation
def test_generated_certificate_has_the_right_names(config):
    result = issue_server_certificate(config.cert_dir,
                                      ["minecraft-pc.tailnet.ts.net", "localhost"],
                                      ["100.101.102.103", "127.0.0.1"])
    info = inspect_certificate(result["cert_path"], result["key_path"])
    assert info.parsed is True
    assert info.covers("minecraft-pc.tailnet.ts.net") is True
    assert info.covers("100.101.102.103") is True
    assert info.covers("evil.example.com") is False
    assert info.key_matches_certificate is True
    assert info.self_signed is False, "the leaf must be signed by the CA, not by itself"


def test_certificate_lifetime_is_browser_acceptable(config):
    result = issue_server_certificate(config.cert_dir, ["localhost"], ["127.0.0.1"])
    info = inspect_certificate(result["cert_path"])
    assert 390 < info.days_remaining <= 398, "browsers reject leaf certificates over 398 days"


def test_reissuing_keeps_the_same_ca(config):
    """Renewal must not force you to re-trust the CA on every device."""
    issue_server_certificate(config.cert_dir, ["localhost"], ["127.0.0.1"])
    ca_bytes = (config.cert_dir / "ca.crt").read_bytes()
    second = issue_server_certificate(config.cert_dir, ["localhost"], ["127.0.0.1"])
    assert (config.cert_dir / "ca.crt").read_bytes() == ca_bytes
    assert inspect_certificate(second["cert_path"], second["key_path"]).key_matches_certificate


def test_mismatched_key_is_detected(config):
    good = issue_server_certificate(config.cert_dir, ["localhost"], ["127.0.0.1"])
    other_dir = config.cert_dir.parent / "other"
    create_ca(other_dir)
    other = issue_server_certificate(other_dir, ["localhost"], ["127.0.0.1"])
    info = inspect_certificate(good["cert_path"], other["key_path"])
    assert info.key_matches_certificate is False


def test_expiry_severity_tiers(config):
    result = issue_server_certificate(config.cert_dir, ["localhost"], ["127.0.0.1"])
    now = time.time()
    assert inspect_certificate(result["cert_path"], now=now).expiry_severity == "ok"
    soon = now + (398 - 10) * 86400
    assert inspect_certificate(result["cert_path"], now=soon).expiry_severity == "warn"
    sooner = now + (398 - 2) * 86400
    assert inspect_certificate(result["cert_path"], now=sooner).expiry_severity == "critical"
    past = now + 400 * 86400
    info = inspect_certificate(result["cert_path"], now=past)
    assert info.expired is True
    assert info.expiry_severity == "critical"


def test_unreadable_certificate_reports_unknown_not_valid(config):
    bad = config.cert_dir
